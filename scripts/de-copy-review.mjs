#!/usr/bin/env node
/**
 * `pnpm gen:de-review` (PLAN-DASH-11 step 4, D-32).
 *
 * Compares `dictionaries/en/<area>.json` with `dictionaries/de/<area>.json` and writes
 * `docs/90_work/notes/2026-10-24_de-copy-review.md`: per area, the English keys that German does
 * not provide yet (the app falls back to English for them). It lists keys only; it translates
 * nothing. `--check` exits with 1 when the note is out of date, `--print` writes to stdout.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
export const NOTE = "docs/90_work/notes/2026-10-24_de-copy-review.md"

const isObject = (value) => typeof value === "object" && value !== null && !Array.isArray(value)

/** Leaf key paths of `base` that `other` does not provide (same rule as `missingKeys` in lib/i18n). */
export function missing(base, other, prefix = "") {
  if (!isObject(base)) return []
  const side = isObject(other) ? other : {}
  return Object.entries(base).flatMap(([key, value]) => {
    const keyPath = prefix ? `${prefix}.${key}` : key
    if (isObject(value)) return missing(value, side[key], keyPath)
    return side[key] === undefined || side[key] === "" ? [keyPath] : []
  })
}

export function leafCount(value) {
  return isObject(value) ? Object.values(value).reduce((sum, child) => sum + leafCount(child), 0) : 1
}

const read = (lang, area) => {
  const file = path.join(ROOT, "dictionaries", lang, `${area}.json`)
  return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : {}
}

/** One entry per dictionary area: totals and the missing keys. */
export function review() {
  return readdirSync(path.join(ROOT, "dictionaries/en"))
    .filter((file) => file.endsWith(".json"))
    .map((file) => file.replace(/\.json$/, ""))
    .sort()
    .map((area) => {
      const en = read("en", area)
      const keys = missing(en, read("de", area))
      return { area, total: leafCount(en), keys }
    })
}

const percent = (part, whole) => (whole === 0 ? 100 : Math.round((part / whole) * 100))

/** Groups key paths by their first two segments, keeping the order of the dictionary. */
function groups(keys) {
  const map = new Map()
  for (const key of keys) {
    const parts = key.split(".")
    const head = parts.length > 2 ? parts.slice(0, 2).join(".") : parts[0]
    map.set(head, [...(map.get(head) ?? []), key])
  }
  return map
}

export function render(areas) {
  const total = areas.reduce((sum, entry) => sum + entry.total, 0)
  const open = areas.reduce((sum, entry) => sum + entry.keys.length, 0)
  const lines = [
    "---",
    "id: NOTE-2026-10-24-de-copy-review",
    "date: 2026-10-24",
    "author: Claude (phase 11 sub-agent), generated by scripts/de-copy-review.mjs",
    "relates_to: [PLAN-DASH-11, D-19, D-32]",
    "---",
    "",
    "# German copy review: what is still English",
    "",
    "What German still lacks (D-32). Every area was translated on 2026-10-24 (v0.4, D-67): the dictionaries and the public docs pages, as a draft for the owner's review. A key missing in DE still shows the English text (`getDictionary` deep-merges DE over EN), so this list should stay empty.",
    "",
    "Regenerate with `pnpm gen:de-review` (`--check` fails when this note is stale, `--print` shows it without writing). Copy lives in `dictionaries/en/<area>.json`; add the same key path to `dictionaries/de/<area>.json`, then run the unit tests (`lib/i18n/dictionaries.test.ts` checks that DE has no key EN lacks).",
    "",
    "Things to check in the translation pass, not just the keys:",
    "",
    "- Numbers and units go through `lib/i18n/format` and are already German; do not translate digits into the text.",
    "- Business Plan presets (`business-plan.presets.*`) are written **into the project** in the UI language when a use case is picked, so they are data as well as copy.",
    "- Equation texts (`calc.*`) explain the formulas of `docs/10_quick-check-tool`; keep the equation IDs (`EQ-3.4a`) unchanged.",
    "- An English value that is empty counts as missing here too (`assumptions.tables.TBL-6.unit`); nothing renders it, so it needs no German.",
    "- The legal areas (`legal`, `terms`, `privacy`, `cookies`, `imprint`, `ai`, `license`) have a complete German draft (D-44). It is **not legally reviewed**: they are not part of this to-do list, but they need the owner's or a lawyer's review before launch (see the phase 12 note).",
    "",
    "## Summary",
    "",
    "| Area | Keys in EN | Missing in DE | DE coverage |",
    "|---|---:|---:|---:|",
    ...areas.map((entry) => `| [${entry.area}](#${entry.area}) | ${entry.total} | ${entry.keys.length} | ${percent(entry.total - entry.keys.length, entry.total)} % |`),
    `| **All** | **${total}** | **${open}** | **${percent(total - open, total)} %** |`,
    "",
  ]
  for (const entry of areas) {
    lines.push(`## ${entry.area}`, "")
    if (entry.keys.length === 0) {
      lines.push("Complete: German provides every key.", "")
      continue
    }
    lines.push(`${entry.keys.length} of ${entry.total} keys missing (\`dictionaries/de/${entry.area}.json\`).`, "")
    for (const [head, keys] of groups(entry.keys)) {
      lines.push(`**\`${head}\`** (${keys.length})`, "", ...keys.map((key) => `- \`${key}\``), "")
    }
  }
  return lines.join("\n").replace(/\n+$/, "\n")
}

function main() {
  const text = render(review())
  const target = path.join(ROOT, NOTE)
  if (process.argv.includes("--print")) {
    process.stdout.write(text)
  } else if (process.argv.includes("--check")) {
    const current = existsSync(target) ? readFileSync(target, "utf8") : ""
    if (current !== text) {
      console.error(`${NOTE} is out of date. Run pnpm gen:de-review.`)
      process.exit(1)
    }
  } else {
    writeFileSync(target, text)
    console.log(`Wrote ${NOTE}`)
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
