#!/usr/bin/env node
/**
 * `pnpm gen:reference` (PLAN-DASH-05 step 1).
 *
 * 1. Converts every `docs/10_quick-check-tool/_reference/*.yaml` into
 *    `lib/quick-check/reference/<name>.gen.ts` (values exactly as in the YAML).
 * 2. Reads the frontmatter `latex:` of every equation file in
 *    `docs/10_quick-check-tool/02_run-quick-check/` and writes
 *    `lib/quick-check/explain/equations.gen.ts`: ID → MathML (KaTeX `output: "mathml"`) plus the
 *    output symbol, for "How we calculate" (D-33). No math library ships to the client.
 *
 * `node scripts/gen-reference.mjs --check` exits with 1 when a generated file is out of date.
 * `scripts/gen-reference.test.ts` runs the same check in `pnpm test`.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import katex from "katex"
import { parse } from "yaml"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")

const QCT = "docs/10_quick-check-tool"
const REFERENCE_DIR = `${QCT}/_reference`
const EQUATION_DIR = `${QCT}/02_run-quick-check`
const OQ_DIR = `${QCT}/open-questions`
export const REFERENCE_OUT = "lib/quick-check/reference"
export const EQUATIONS_OUT = "lib/quick-check/explain/equations.gen.ts"

/**
 * Formulas that no equation file holds, written from the resolved OQ answer (the only math
 * that is not a `latex:` field). They render with their OQ ID as the source.
 */
const RESOLVED_FORMULAS = [
  {
    // With PV, EQ-3.11 times (1 − PV cost reduction of TBL-6, 30 % by default); r_PV names that row.
    id: "OQ-06",
    output: "C_{el,PV}",
    latex: "C_{el,PV} = C_{el} \\cdot (1 - r_{PV})",
  },
  {
    id: "OQ-12",
    output: "CH",
    latex: "CH = \\frac{\\min(Q_{cool,total}, Q_{heat,total})}{\\max(Q_{cool,total}, Q_{heat,total})}",
  },
  {
    // EQ-3.10d without the second C_i: the installations are counted once.
    id: "OQ-17",
    output: "C_{overall}",
    latex: "C_{overall} = C_{HP} \\cdot N_{total} + C_{net} + C_{i,total}",
  },
  {
    id: "OQ-21",
    output: "E",
    latex: "E = \\frac{R_{overall}}{C_{annual} + C_{el} + C_{O\\&M}}",
  },
]

/**
 * `C_{O\&M} = …` → MathML string (KaTeX `output: "mathml"`). Equations render in display mode
 * (`<math display="block">`: sum limits above and below, full-size fractions); output symbols
 * render inline.
 */
export function toMathml(latex, { display = false } = {}) {
  return katex.renderToString(latex, { output: "mathml", displayMode: display, throwOnError: true, strict: "error" })
}

/** `table-01_annual-heating-demand.yaml` → `table-01-annual-heating-demand`. */
function stemOf(file) {
  return path.basename(file, path.extname(file)).replaceAll("_", "-")
}

/** `TBL-1` → `TBL_1`; files without an id use their name (`symbols` → `SYMBOLS`). */
function exportNameOf(id, file) {
  return (id ?? stemOf(file)).toUpperCase().replace(/[^A-Z0-9]+/g, "_")
}

/** The YAML block between the first two `---` lines of a markdown file. */
export function frontmatterOf(markdown, file) {
  const match = markdown.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n/)
  if (!match) throw new Error(`${file}: no frontmatter`)
  return parse(match[1])
}

function header(sources) {
  return [
    "// Generated by scripts/gen-reference.mjs from",
    ...sources.map((source) => `//   ${source}`),
    "// Do not edit. Run `pnpm gen:reference` after changing the source.",
    "",
  ].join("\n")
}

function literal(value) {
  return JSON.stringify(value, null, 2)
}

function readText(root, relative) {
  return readFileSync(path.join(root, relative), "utf8")
}

function listFiles(root, relative, filter) {
  return readdirSync(path.join(root, relative)).filter(filter).sort()
}

/** One `.gen.ts` per reference YAML: `export const TBL_1 = { … } as const`. */
function referenceFiles(root) {
  return listFiles(root, REFERENCE_DIR, (file) => file.endsWith(".yaml")).map((file) => {
    const source = `${REFERENCE_DIR}/${file}`
    const data = parse(readText(root, source))
    const name = exportNameOf(data.id, file)
    return {
      path: `${REFERENCE_OUT}/${stemOf(file)}.gen.ts`,
      content: `${header([source])}\nexport const ${name} = ${literal(data)} as const\n`,
    }
  })
}

function formula({ id, slug, title, file, output, latex, inputs, tables, flags }) {
  return {
    id,
    slug,
    title,
    file,
    output: output ?? null,
    outputMathml: output ? toMathml(output) : null,
    latex: latex ?? null,
    mathml: latex ? toMathml(latex, { display: true }) : null,
    inputs: inputs ?? [],
    tables: tables ?? [],
    flags: flags ?? [],
  }
}

function equationsFile(root) {
  const sources = []
  const equations = listFiles(root, EQUATION_DIR, (file) => file.startsWith("eq-") && file.endsWith(".md")).map(
    (file) => {
      const relative = `${EQUATION_DIR}/${file}`
      sources.push(relative)
      const front = frontmatterOf(readText(root, relative), relative)
      return formula({ ...front, slug: file.split("_")[0], file: relative })
    },
  )
  const resolved = RESOLVED_FORMULAS.map((entry) => {
    const file = listFiles(root, OQ_DIR, (name) => name.startsWith(`${entry.id}_`))[0]
    if (!file) throw new Error(`${entry.id}: no open-question file`)
    const relative = `${OQ_DIR}/${file}`
    sources.push(relative)
    const front = frontmatterOf(readText(root, relative), relative)
    if (front.status !== "resolved") throw new Error(`${entry.id} is not resolved`)
    return formula({ ...entry, slug: entry.id.toLowerCase(), title: front.title, file: relative, flags: [entry.id] })
  })
  const byId = (list) => Object.fromEntries(list.map((entry) => [entry.id, entry]))
  const content = [
    header(sources),
    "/** Every equation of methodology §3 (`latex:` of each file), keyed by ID, in file order. */",
    `export const EQUATIONS = ${literal(byId(equations))} as const`,
    "",
    "/** Formulas that come from a resolved OQ answer instead of an equation file (OQ-06, OQ-12, OQ-17, OQ-21). */",
    `export const RESOLVED_FORMULAS = ${literal(byId(resolved))} as const`,
    "",
  ].join("\n")
  return { path: EQUATIONS_OUT, content }
}

/** Every generated file with its content, relative to `root`. Pure: writes nothing. */
export function generateReference(root = ROOT) {
  return [...referenceFiles(root), equationsFile(root)]
}

/** Generated files on disk that the generator no longer produces (a YAML was removed). */
export function staleFiles(root, files) {
  const expected = new Set(files.map((file) => file.path))
  return listFiles(root, REFERENCE_OUT, (file) => file.endsWith(".gen.ts"))
    .map((file) => `${REFERENCE_OUT}/${file}`)
    .filter((file) => !expected.has(file))
}

/** Paths whose content on disk differs from the generator's output (missing files included). */
export function outdatedFiles(root, files) {
  return files
    .filter((file) => {
      const target = path.join(root, file.path)
      return !existsSync(target) || readFileSync(target, "utf8") !== file.content
    })
    .map((file) => file.path)
}

function main() {
  const files = generateReference(ROOT)
  const outdated = outdatedFiles(ROOT, files)
  const stale = existsSync(path.join(ROOT, REFERENCE_OUT)) ? staleFiles(ROOT, files) : []
  if (process.argv.includes("--check")) {
    for (const file of [...outdated, ...stale]) console.error(`out of date: ${file}`)
    process.exit(outdated.length + stale.length > 0 ? 1 : 0)
  }
  for (const file of files) {
    const target = path.join(ROOT, file.path)
    mkdirSync(path.dirname(target), { recursive: true })
    if (outdated.includes(file.path)) writeFileSync(target, file.content)
  }
  for (const file of stale) unlinkSync(path.join(ROOT, file))
  console.log(`gen:reference: ${files.length} files, ${outdated.length} written, ${stale.length} removed`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
